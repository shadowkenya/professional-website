    $req_id = intval($_POST['request_id']);
    $update = $conn->prepare("UPDATE contact_requests SET status = 'completed' WHERE id = ?");
    if ($update) {
        $update->bind_param("i", $req_id);
        $update->execute();
        $update->close();
    }
    header("Location: dashboard.php?view=" . ($_GET['view'] ?? 'pending'));
    exit;
}

// 2. Action: Erase and Wipe All Completed Log Rows entirely
