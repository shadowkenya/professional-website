$log_traffic = $conn->prepare("INSERT INTO traffic_log (ip_address, session_id, last_activity) 
                               VALUES (?, ?, NOW()) 
                               ON DUPLICATE KEY UPDATE last_activity = NOW(), ip_address = ?");
if ($log_traffic) {
    $log_traffic->bind_param("sss", $ip_address, $session_id, $ip_address);
    $log_traffic->execute();
    $log_traffic->close();
}

