    $live_query = $conn->query("SELECT view_count AS live_total FROM site_analytics WHERE id = 1");
    $live_count = $live_query ? $live_query->fetch_assoc()['live_total'] : 0;
} else {
    // Structural fallback option: tracking live logs within active session bounds
    $live_query = $conn->query("SELECT COUNT(*) as live_total FROM traffic_log");
    $live_count = $live_query ? $live_query->fetch_assoc()['live_total'] : 0;
